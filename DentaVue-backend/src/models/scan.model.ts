import { supabaseAdmin } from '@/config/supabase.js'
import type { IsoDateTime } from '@/types/domain.js'

/**
 * The "M" in MVC: all database access for `public.scans` and its per-angle
 * `public.scan_images` (see 0003_scans.sql, 0004_scan_images.sql).
 *
 * A scan is one guided-capture session. Its bytes live in Supabase Storage; the
 * `scans` row holds the front-teeth cover's path plus metadata, and `scan_images`
 * holds every angle of the session. Models own persistence only — no Storage
 * calls, no signing, no HTTP: the service composes those.
 *
 * Rows are snake_case; the domain is camelCase. This layer maps between them.
 */

export interface ScanRow {
  id: string
  user_id: string
  storage_path: string
  captured_at: IsoDateTime
  score: number | null
  created_at: IsoDateTime
}

export interface Scan {
  id: string
  userId: string
  storagePath: string
  capturedAt: IsoDateTime
  score: number | null
  createdAt: IsoDateTime
}

/** One angle of a capture session (a row of `scan_images`). */
export interface ScanImage {
  position: number
  angle: string
  storagePath: string
}

/** A scan plus its per-angle images, in capture order (position ascending). */
export interface ScanWithImages extends Scan {
  images: ScanImage[]
}

const TABLE = 'scans'
const IMAGES_TABLE = 'scan_images'

function toDomain(row: ScanRow): Scan {
  return {
    id: row.id,
    userId: row.user_id,
    storagePath: row.storage_path,
    capturedAt: row.captured_at,
    score: row.score,
    createdAt: row.created_at,
  }
}

export async function create(input: {
  /** Generated by the service (it also names the Storage object with it). */
  id: string
  userId: string
  storagePath: string
  capturedAt: IsoDateTime
  score?: number | null
}): Promise<Scan> {
  const { data, error } = await supabaseAdmin
    .from(TABLE)
    .insert({
      id: input.id,
      user_id: input.userId,
      storage_path: input.storagePath,
      captured_at: input.capturedAt,
      score: input.score ?? null,
    })
    .select('*')
    .single()

  if (error) throw error
  return toDomain(data as ScanRow)
}

/**
 * The caller's scans, oldest first (newest last), each with its per-angle images
 * (position ascending) joined from `scan_images`.
 */
export async function listByUser(userId: string): Promise<ScanWithImages[]> {
  const { data, error } = await supabaseAdmin
    .from(TABLE)
    .select('*, scan_images(position, angle, storage_path)')
    .eq('user_id', userId)
    .order('captured_at', { ascending: true })

  if (error) throw error

  type Row = ScanRow & {
    scan_images: { position: number; angle: string; storage_path: string }[] | null
  }
  return (data as Row[]).map((row) => ({
    ...toDomain(row),
    images: (row.scan_images ?? [])
      .slice()
      .sort((a, b) => a.position - b.position)
      .map((image) => ({
        position: image.position,
        angle: image.angle,
        storagePath: image.storage_path,
      })),
  }))
}

/**
 * One scan with its images, scoped to its owner.
 *
 * The user id is part of the QUERY, not checked afterwards: a caller who guesses
 * another user's scan uuid gets null, not a row they then have to be trusted not
 * to read. Authorization is the API's job here — the service-role key bypasses
 * RLS, so the database will not catch this.
 */
export async function findByIdForUser(
  id: string,
  userId: string,
): Promise<ScanWithImages | null> {
  const { data, error } = await supabaseAdmin
    .from(TABLE)
    .select('*, scan_images(position, angle, storage_path)')
    .eq('id', id)
    .eq('user_id', userId)
    .maybeSingle()

  if (error) throw error
  if (!data) return null

  type Row = ScanRow & {
    scan_images: { position: number; angle: string; storage_path: string }[] | null
  }
  const row = data as Row
  return {
    ...toDomain(row),
    images: (row.scan_images ?? [])
      .slice()
      .sort((a, b) => a.position - b.position)
      .map((image) => ({
        position: image.position,
        angle: image.angle,
        storagePath: image.storage_path,
      })),
  }
}

/**
 * Records the computed oral-health score.
 *
 * Denormalised from scan_analysis on purpose: the list endpoint returns a score
 * per scan, and duplicating one smallint is cheaper than joining every read.
 * analysis.service writes both, so they cannot drift apart.
 */
export async function setScore(id: string, score: number): Promise<void> {
  const { error } = await supabaseAdmin.from(TABLE).update({ score }).eq('id', id)
  if (error) throw error
}

/**
 * Removes a scan row. Used by the service to undo a half-written session when
 * the per-angle image inserts fail after the scan row was created (its Storage
 * objects are removed separately). Cascade drops any scan_images already linked.
 */
export async function remove(id: string): Promise<void> {
  const { error } = await supabaseAdmin.from(TABLE).delete().eq('id', id)
  if (error) throw error
}

/**
 * Records every angle of a capture session. Called once per scan, after the
 * `scans` row exists (the FK requires it). All rows insert together.
 */
export async function createImages(
  images: Array<{ scanId: string; position: number; angle: string; storagePath: string }>,
): Promise<void> {
  const { error } = await supabaseAdmin.from(IMAGES_TABLE).insert(
    images.map((image) => ({
      scan_id: image.scanId,
      position: image.position,
      angle: image.angle,
      storage_path: image.storagePath,
    })),
  )
  if (error) throw error
}
